const departamentos = [
  { id: 'dept-admin', nome: 'ADMIN' },
  { id: 'dept-producao', nome: 'PRODUÇÃO' },
  { id: 'dept-deposito', nome: 'DEPOSITO' },
  { id: 'dept-obra', nome: 'OBRA' }
];

const deptMap = {
  'ADMIN': 'dept-admin',
  'PRODUÇÃO': 'dept-producao',
  'DEPOSITO': 'dept-deposito',
  'OBRA': 'dept-obra'
};

let currentBranchId = 'branch-1';
const colaboradores = [];

for (const line of lines) {
  const trimmed = line.trim();
  if (!trimmed || trimmed === ';;;' || trimmed.startsWith('Código Cracha')) continue;
  
  if (trimmed.startsWith('EMPRESA:')) {
    if (trimmed.includes('Navirai')) {
      currentBranchId = 'branch-2';
    } else if (trimmed.includes('DISTRIBUIDORA')) {
      currentBranchId = 'branch-3';
    } else if (trimmed.includes('CAIARI')) {
      currentBranchId = 'branch-4';
    } else {
      currentBranchId = 'branch-1';
    }
    continue;
  }

  const parts = trimmed.split(';').map(s => s.trim()).filter(Boolean);
  if (parts.length >= 4) {
    const cracha = parseInt(parts[0], 10);
    const nome = parts[1];
    const dataAdmParts = parts[2].split('/');
    const admissao = `${dataAdmParts[2]}-${dataAdmParts[1]}-${dataAdmParts[0]}`;
    const deptoRaw = parts[3];
    const deptId = deptMap[deptoRaw] || 'dept-admin';
    
    colaboradores.push({
      id: `colab_${currentBranchId}_${cracha}`,
      cracha,
      nome,
      filialId: currentBranchId,
      deptId,
      admissao,
      registraPonto: true,
      status: 'ativo',
      dataDemissao: ''
    });
  }
}

console.log('Total Colaboradores extraídos:', colaboradores.length);
console.log('Por Filial:', {
  'branch-1': colaboradores.filter(c => c.filialId === 'branch-1').length,
  'branch-2': colaboradores.filter(c => c.filialId === 'branch-2').length,
  'branch-3': colaboradores.filter(c => c.filialId === 'branch-3').length,
  'branch-4': colaboradores.filter(c => c.filialId === 'branch-4').length,
});

fs.writeFileSync('./parsed_data.json', JSON.stringify({ filiais, departamentos, colaboradores }, null, 2));
